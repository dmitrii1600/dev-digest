const SLUG_MAX = 60;

export function slugify(name: string): string {
  const s = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, SLUG_MAX)
    .replace(/-+$/g, '');
  return s || 'agent';
}

/** Slugs for `names` in order; a collision gets `-2`, `-3`, … */
export function uniqueSlugs(names: string[]): string[] {
  const seen = new Set<string>();
  return names.map((n) => {
    const base = slugify(n);
    let slug = base;
    for (let i = 2; seen.has(slug); i++) slug = `${base}-${i}`;
    seen.add(slug);
    return slug;
  });
}

export interface ManifestAgent {
  name: string;
  provider: string;
  model: string;
  systemPrompt: string;
  strategy: string;
  ciFailOn: CiFailOn;
}

/** The `.devdigest/agents/<slug>.yaml` text — parses under `AgentManifest`. */
export function buildManifestYaml(agent: ManifestAgent, skillSlugs: string[]): string {
  return stringify({
    name: agent.name,
    provider: agent.provider,
    model: agent.model,
    system_prompt: agent.systemPrompt,
    skills: skillSlugs,
    strategy: agent.strategy,
    ci_fail_on: agent.ciFailOn,
  });
}

const TRIGGER_ORDER: CiTrigger[] = ['opened', 'synchronize', 'reopened'];

/**
 * The fixed workflow template. Only the closed-set trigger list and the
 * `DEVDIGEST_POST_AS` literal vary — no agent or user text is interpolated.
 */
export function buildWorkflowYaml(opts: { triggers: CiTrigger[]; postAs: CiPostAs }): string {
  const types = TRIGGER_ORDER.filter((t) => opts.triggers.includes(t)).join(', ');
  return `# Generated by DevDigest — Export to CI. "Update CI config" regenerates this file.
name: DevDigest Review
on:
  pull_request:
    types: [${types}]
permissions:
  contents: read
  pull-requests: write
jobs:
  review:
    name: DevDigest Review
    if: github.event.pull_request.head.repo.full_name == github.repository
    runs-on: ubuntu-latest
    steps:
      - uses: ${PINNED_ACTIONS.checkout}
        with:
          persist-credentials: false
      - uses: ${PINNED_ACTIONS.setupNode}
        with:
          node-version: 22
      - name: Run DevDigest review
        run: node .devdigest/runner/index.js
        env:
          OPENROUTER_API_KEY: \${{ secrets.OPENROUTER_API_KEY }}
          GITHUB_TOKEN: \${{ github.token }}
          PR_NUMBER: \${{ github.event.pull_request.number }}
          DEVDIGEST_POST_AS: ${opts.postAs}
      - name: Upload result
        if: always()
        uses: ${PINNED_ACTIONS.uploadArtifact}
        with:
          name: devdigest-result
          path: devdigest-result.json
          if-no-files-found: ignore
`;
}

export function buildMemoryJsonl(rows: { kind: string; content: string }[]): string {
  if (rows.length === 0) return '';
  return rows.map((r) => JSON.stringify({ kind: r.kind, content: r.content })).join('\n') + '\n';
}

export interface AssembleInput {
  manifestPath: string;
  manifestYaml: string;
  skills: { slug: string; body: string }[];
  memoryJsonl: string;
  runner: { name: string; contents: string }[];
  includeGitattributes: boolean;
  workflowYaml: string;
}

/** The exported file set, in preview order. Only the workflow is editable. */
export function assembleFiles(input: AssembleInput): CiFile[] {
  const files: CiFile[] = [
    { path: input.manifestPath, contents: input.manifestYaml, editable: false },
    ...input.skills.map((s) => ({
      path: `${SKILLS_DIR}/${s.slug}.md`,
      contents: s.body,
      editable: false,
    })),
    { path: MEMORY_PATH, contents: input.memoryJsonl, editable: false },
    ...input.runner.map((f) => ({
      path: `${RUNNER_DIR}/${f.name}`,
      contents: f.contents,
      editable: false,
    })),
  ];
  if (input.includeGitattributes) {
    files.push({ path: GITATTRIBUTES_PATH, contents: GITATTRIBUTES_BODY, editable: false });
  }
  files.push({ path: WORKFLOW_PATH, contents: input.workflowYaml, editable: true });
  return files;
}

export function validateWorkflowYaml(text: string): { ok: true } | { ok: false; error: string } {
  if (Buffer.byteLength(text, 'utf8') > CI_MAX_BYTES) {
    return { ok: false, error: `Workflow is larger than ${CI_MAX_BYTES} bytes` };
  }
  try {
    parse(text);
    return { ok: true };
  } catch (err) {
    return { ok: false, error: err instanceof Error ? err.message : String(err) };
  }
}

export type VerifyResult =
  | { kind: 'accepted'; artifact: CiResultArtifact }
  | { kind: 'rejected' }
  | { kind: 'no_result' };

/**
 * Accept a run only when it belongs to this installation: same repository id,
 * exact workflow path, a head SHA, a result that parses and a PR number the
 * run is actually attached to.
 */
export function verifyRun(
  inst: { githubRepoId: number },
  run: WorkflowRunMeta,
  dl: ArtifactDownload,
): VerifyResult {
  if (run.repository_id !== inst.githubRepoId) return { kind: 'rejected' };
  if (run.path.split('@')[0] !== WORKFLOW_PATH) return { kind: 'rejected' };
  if (!run.head_sha) return { kind: 'rejected' };
  if (dl.kind === 'missing' || dl.kind === 'expired') return { kind: 'no_result' };
  if (dl.kind === 'too_large') return { kind: 'rejected' };
  let json: unknown;
  try {
    json = JSON.parse(dl.text);
  } catch {
    return { kind: 'rejected' };
  }
  const parsed = CiResultArtifact.safeParse(json);
  if (!parsed.success) return { kind: 'rejected' };
  const artifact = parsed.data;
  if (artifact.pr_number == null || !run.pull_requests.includes(artifact.pr_number)) {
    return { kind: 'rejected' };
  }
  return { kind: 'accepted', artifact };
}

/** How many findings would fail the CI check under `ciFailOn`. */
export function countBlockers(
  counts: { critical?: number | null; warning?: number | null; suggestion?: number | null },
  ciFailOn: CiFailOn,
): number {
  const c = counts.critical ?? 0;
  const w = counts.warning ?? 0;
  const s = counts.suggestion ?? 0;
  switch (ciFailOn) {
    case 'critical':
      return c;
    case 'warning':
      return c + w;
    case 'any':
      return c + w + s;
    default:
      return 0;
  }
}

export function runStatus(artifact: CiResultArtifact): 'succeeded' | 'no_findings' {
  return artifact.findings_count > 0 ? 'succeeded' : 'no_findings';
}

export interface CiTraceInput {
  agentName: string;
  agentVersion: number;
  model: string;
  provider: string;
  prNumber: number | null;
  artifact: CiResultArtifact | null;
  headSha: string;
  skills: string[];
  runnerSha256: string;
  jobUrl: string;
}

export function buildCiTrace(i: CiTraceInput): RunTrace {
  const line = (msg: string) => ({ t: '00.00', kind: 'info' as const, msg });
  return {
    config: {
      agent: i.agentName,
      version: String(i.agentVersion),
      provider: i.provider,
      model: i.model,
      pr: i.prNumber,
      source: 'ci',
    },
    stats: {
      duration_ms: i.artifact?.duration_ms ?? 0,
      tokens_in: 0,
      tokens_out: 0,
      cost_usd: i.artifact?.cost_usd ?? null,
      findings: i.artifact?.findings_count ?? 0,
      grounding: '',
    },
    prompt_assembly: { system: '', user: '' },
    tool_calls: [],
    raw_output: '',
    memory_pulled: [],
    specs_read: [],
    log: [
      line(`commit ${i.headSha}`),
      line(`manifest version ${i.agentVersion}`),
      line(`model ${i.model}`),
      line(`skills ${i.skills.join(', ')}`),
      line(`runner sha256 ${i.runnerSha256}`),
      line(`job ${i.jobUrl}`),
    ],
  };
}

/** Zip of `files` keyed by repo path, base64-encoded. */
export function buildZipBase64(files: CiFile[]): string {
  const entries: Record<string, Uint8Array> = {};
  for (const f of files) entries[f.path] = strToU8(f.contents);
  return Buffer.from(zipSync(entries)).toString('base64');
}
